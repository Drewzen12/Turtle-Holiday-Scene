import turtle
t = turtle.Turtle()
t.speed(0)
t.color("blue")
def christmas_treetop(x,y):
     t.teleport(x,y)
    
     t.color("green")
     t.begin_fill()
     t.left(45)
     t.forward(141.42)
     t.right(90)
     t.forward(141.42)
     t.right(135)
     t.forward(200)
     t.right(180)
     t.end_fill()
def christmas_trunk():
     t.color("brown")
     t.begin_fill()
     t.forward(80)
     t.right(90)
     t.forward(50)
     t.left(90)
     t.forward(50)
     t.left(90)
     t.forward(50)
     t.right(90)
     t.end_fill()

def present(x,y,color):
    t.teleport(x,y)
    t.color(color)
    t.begin_fill()
    for i in range(4):
         t.forward(50)
         t.right(90)
    t.end_fill()
    t.penup()
    t.forward(25)
    t.right(90)
    t.color("yellow")
    t.pendown()
    t.pensize(5)
    t.forward(50)
    t.penup()
    t.right(180)
    t.forward(50)
    t.left(90)
    t.forward(50)
    t.right(180)
    t.pendown()
if __name__ == "__main__":

    present(-150,120, "red")
    present(-50,120, "blue")
    present(50,120, "red")
    christmas_treetop(-100,300)
    christmas_treetop(-100,250)
    christmas_treetop(-100,200)
    christmas_trunk()
   
turtle.done()
